create or replace function private.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  row_data jsonb;
  target_brand_id uuid;
  target_organization_id uuid;
  target_entity_id uuid;
begin
  row_data := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  target_brand_id := nullif(row_data ->> 'brand_id', '')::uuid;
  target_organization_id := nullif(row_data ->> 'organization_id', '')::uuid;
  target_entity_id := nullif(row_data ->> 'id', '')::uuid;

  if tg_table_name = 'brands' then
    target_brand_id := target_entity_id;
  end if;

  if target_organization_id is null and target_brand_id is not null then
    select b.organization_id into target_organization_id from public.brands b where b.id = target_brand_id;
  end if;

  if target_organization_id is not null then
    insert into public.activity_logs (
      organization_id, brand_id, actor_user_id, action, entity_type, entity_id, old_data, new_data
    ) values (
      target_organization_id,
      target_brand_id,
      (select auth.uid()),
      lower(tg_table_name || '.' || tg_op),
      tg_table_name,
      target_entity_id,
      case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end,
      case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end
    );
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

revoke all on function private.audit_row_change() from public, anon, authenticated;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'brands','memberships','pharmacies','products','product_references','agent_brand_assignments',
    'pharmacy_assignments','orders','missions','mission_reports'
  ] loop
    execute format('create trigger audit_%I after insert or update or delete on public.%I for each row execute function private.audit_row_change()', table_name, table_name);
  end loop;
end $$;

create or replace function private.has_global_role(role_keys text[])
returns boolean
language sql stable security definer set search_path = ''
as $$
  select (select auth.uid()) is not null and exists (
    select 1 from public.memberships m
    join public.roles r on r.id = m.role_id
    where m.user_id = (select auth.uid()) and m.status = 'active'
      and m.brand_id is null and r.key = any(role_keys)
  );
$$;

create or replace function private.has_brand_role(target_brand_id uuid, role_keys text[])
returns boolean
language sql stable security definer set search_path = ''
as $$
  select (select auth.uid()) is not null and (
    private.has_global_role(array['super_admin']) or exists (
      select 1 from public.memberships m
      join public.roles r on r.id = m.role_id
      where m.user_id = (select auth.uid()) and m.status = 'active'
        and m.brand_id = target_brand_id and r.key = any(role_keys)
    )
  );
$$;

create or replace function private.has_brand_permission(target_brand_id uuid, permission_key text)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select private.has_global_role(array['super_admin']) or coalesce((
    select bool_or(coalesce(m.permissions ->> permission_key, r.permissions ->> permission_key)::boolean)
    from public.memberships m
    join public.roles r on r.id = m.role_id
    where m.user_id = (select auth.uid()) and m.status = 'active' and m.brand_id = target_brand_id
  ), false);
$$;

create or replace function private.can_assign_role(target_brand_id uuid, target_role_id smallint)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select private.has_global_role(array['super_admin']) or exists (
    select 1
    from public.roles target_role
    where target_role.id = target_role_id
      and target_role.key not in ('super_admin', 'tr1_manager')
      and target_role.rank <= coalesce((
        select max(author_role.rank)
        from public.memberships author_membership
        join public.roles author_role on author_role.id = author_membership.role_id
        where author_membership.user_id = (select auth.uid())
          and author_membership.brand_id = target_brand_id
          and author_membership.status = 'active'
      ), 0)
  );
$$;

create or replace function private.can_access_brand(target_brand_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select private.has_global_role(array['super_admin']) or exists (
    select 1 from public.memberships m
    where m.user_id = (select auth.uid()) and m.status = 'active' and m.brand_id = target_brand_id
  );
$$;

create or replace function private.has_elevated_brand_access(target_brand_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select private.has_brand_role(target_brand_id, array['tr1_manager','brand_admin','brand_user']);
$$;

create or replace function public.can_manage_brand_users(target_brand_id uuid)
returns boolean language sql stable security invoker set search_path = '' as $$
  select private.has_brand_permission(target_brand_id, 'users.manage');
$$;

create or replace function public.get_my_brand_contexts()
returns table (brand_id uuid, brand_name text, brand_slug text, role_key text)
language sql stable security invoker set search_path = '' as $$
  select b.id, b.name, b.slug,
    case
      when private.has_global_role(array['super_admin']) then 'super_admin'
      else (
        select r.key from public.memberships m
        join public.roles r on r.id = m.role_id
        where m.user_id = (select auth.uid()) and m.brand_id = b.id and m.status = 'active'
        order by r.id limit 1
      )
    end
  from public.brands b
  where b.is_active and private.can_access_brand(b.id)
  order by b.name;
$$;

create or replace function private.can_manage_user(target_user_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select private.has_global_role(array['super_admin']) or exists (
    select 1 from public.memberships target
    where target.user_id = target_user_id and target.brand_id is not null
      and private.has_brand_role(target.brand_id, array['tr1_manager','brand_admin'])
  );
$$;

create or replace function private.can_access_pharmacy(target_pharmacy_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.pharmacies p where p.id = target_pharmacy_id and (
      private.has_elevated_brand_access(p.brand_id) or exists (
        select 1 from public.pharmacy_assignments pa
        join public.agents a on a.id = pa.agent_id
        where pa.pharmacy_id = p.id and a.user_id = (select auth.uid())
          and pa.starts_at <= current_date and (pa.ends_at is null or pa.ends_at >= current_date)
      )
    )
  );
$$;

create or replace function private.can_access_mission(target_mission_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.missions m where m.id = target_mission_id and (
      private.has_elevated_brand_access(m.brand_id) or m.intervenor_user_id = (select auth.uid())
    )
  );
$$;

