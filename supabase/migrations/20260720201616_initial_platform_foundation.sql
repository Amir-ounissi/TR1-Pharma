create or replace function private.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'organizations','brands','users','user_profiles','memberships','groups','territories',
    'pharmacies','pharmacy_contacts','products','product_references','agents','interactions',
    'tasks','orders','missions','mission_reports'
  ] loop
    execute format('create trigger set_%I_updated_at before update on public.%I for each row execute function private.set_updated_at()', table_name, table_name);
  end loop;
end $$;

create or replace function private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.users (id, email) values (new.id, coalesce(new.email, ''));
  insert into public.user_profiles (user_id, full_name)
  values (new.id, nullif(new.raw_user_meta_data ->> 'full_name', ''));
  return new;
end;
$$;

revoke all on function private.handle_new_auth_user() from public, anon, authenticated;
create trigger on_auth_user_created after insert on auth.users
for each row execute function private.handle_new_auth_user();

create or replace function private.activate_invited_memberships()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.onboarding_completed_at is null and new.onboarding_completed_at is not null then
    update public.memberships set status = 'active' where user_id = new.user_id and status = 'invited';
  end if;
  return new;
